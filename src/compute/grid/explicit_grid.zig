test "initialize grid tracks" {
    const gpa = testing.allocator;
    const minpx0 = MinTrackSizingFunction.fromLength(0.0);
    const minpx20 = MinTrackSizingFunction.fromLength(20.0);
    const minpx100 = MinTrackSizingFunction.fromLength(100.0);

    const maxpx0 = MaxTrackSizingFunction.fromLength(0.0);
    const maxpx20 = MaxTrackSizingFunction.fromLength(20.0);
    const maxpx100 = MaxTrackSizingFunction.fromLength(100.0);

    // Setup test
    const cols = [_]GridTemplateComponent{
        GridTemplateComponent.fromLength(100.0),
        GridTemplateComponent.fromMinMax(.{ .min = MinTrackSizingFunction.fromLength(100.0), .max = MaxTrackSizingFunction.fr(2.0) }),
        GridTemplateComponent.fromFr(1.0),
    };
    const auto_cols = [_]TrackSizingFunction{ TrackSizingFunction.auto, len(100.0) };
    var grid_style: Style = .{ .display = .grid };
    grid_style.gap = Size(LengthPercentage).length(20.0);
    grid_style.grid_template_columns = &cols;
    grid_style.grid_auto_columns = &auto_cols;
    const track_counts: TrackCounts = .{ .negative_implicit = 3, .explicit = @intCast(cols.len), .positive_implicit = 3 };

    // Call function
    var tracks: std.ArrayList(GridTrack) = .empty;
    defer tracks.deinit(gpa);
    try initializeGridTracks(gpa, &tracks, track_counts, &grid_style, .horizontal, 0, NoItems{});

    // Assertions
    const Expected = struct { GridTrackKind, MinTrackSizingFunction, MaxTrackSizingFunction };
    const auto_min = MinTrackSizingFunction.auto;
    const auto_max = MaxTrackSizingFunction.auto;
    const expected = [_]Expected{
        // Gutter
        .{ .gutter, minpx0, maxpx0 },
        // Negative implicit tracks
        .{ .track, minpx100, maxpx100 },
        .{ .gutter, minpx20, maxpx20 },
        .{ .track, auto_min, auto_max },
        .{ .gutter, minpx20, maxpx20 },
        .{ .track, minpx100, maxpx100 },
        .{ .gutter, minpx20, maxpx20 },
