/// The auto-repeat fit strategy to use
pub const AutoRepeatStrategy = enum {
    /// If the grid container has a definite size or max size in the relevant axis:
    ///   - then the number of repetitions is the largest possible positive integer that does not cause the grid to overflow the content
    ///     box of its grid container.
    max_repetitions_that_do_not_overflow,
    /// Otherwise, if the grid container has a definite min size in the relevant axis:
    ///   - then the number of repetitions is the smallest possible positive integer that fulfills that minimum requirement
    min_repetitions_that_do_overflow,
};

/// The result of `computeExplicitGridSizeInAxis`: (auto repetition count, explicit track count)
pub const ExplicitGridSize = struct { u16, u16 };

/// ...treating each track as its max track sizing function if that is definite or as its minimum track sizing function
/// otherwise, flooring the max track sizing function by the min track sizing function if both are definite
fn trackDefiniteValue(sizing_function: TrackSizingFunction, parent_size: ?f32, calc_resolver: anytype) f32 {
    const max_size = sizing_function.max.definiteValue(parent_size, calc_resolver);
    const min_size = sizing_function.min.definiteValue(parent_size, calc_resolver);
    return if (max_size) |max| maybeMax(max, min_size) else min_size.?;
}

/// Compute the number of rows and columns in the explicit grid
///
/// `calc_resolver` is any value with a `resolveCalcValue(ptr, basis) f32` method (usually the tree).
pub fn computeExplicitGridSizeInAxis(
    style: anytype,
    auto_fit_container_size: ?f32,
    auto_fit_strategy: AutoRepeatStrategy,
    calc_resolver: anytype,
    axis: AbsoluteAxis,
) ExplicitGridSize {
    const maybe_template: ?[]const GridTemplateComponent = switch (axis) {
        .horizontal => style.getGridTemplateColumns(),
        .vertical => style.getGridTemplateRows(),
    };
    const template = maybe_template orelse return .{ 0, 0 };

    // If template contains no tracks, then there are trivially zero explicit tracks
    const track_count = template.len;
    if (track_count == 0) {
        return .{ 0, 0 };
    }

    // If there are any repetitions that contains no tracks, then the whole definition should be considered invalid
    // and we default to no explicit tracks
    for (template) |track_def| {
        switch (track_def) {
            .single => {},
            .repeat => |repeat| if (repeat.getTrackCount() == 0) return .{ 0, 0 },
        }
    }

    // Compute that number of track generated by single track definition and repetitions with a fixed repetition count
    // (clamping to the maximum track limit to prevent arithmetic overflow)
    var non_auto_repeating_track_count_u32: u32 = 0;
    for (template) |track_def| {
        const additional_tracks: u32 = switch (track_def) {
            .single => 1,
            .repeat => |repeat| switch (repeat.getCount()) {
                .count => |count| @as(u32, count) * @as(u32, repeat.getTrackCount()),
                .auto_fit, .auto_fill => 0,
            },
        };
        non_auto_repeating_track_count_u32 +|= additional_tracks;
    }
    const non_auto_repeating_track_count: u16 = @intCast(@min(non_auto_repeating_track_count_u32, @as(u32, max_grid_tracks)));

    var auto_repetition_count: u16 = 0;
    var all_track_defs_have_fixed_component = true;
    for (template) |track_def| {
        if (track_def.isAutoRepetition()) auto_repetition_count += 1;
        const has_fixed_component = switch (track_def) {
            .single => |sizing_function| sizing_function.hasFixedComponent(),
            .repeat => |repeat| blk: {
                for (repeat.getTracks()) |sizing_function| {
                    if (!sizing_function.hasFixedComponent()) break :blk false;
                }
                break :blk true;
            },
        };
        if (!has_fixed_component) all_track_defs_have_fixed_component = false;
    }

    const template_is_valid = auto_repetition_count == 0 or (auto_repetition_count == 1 and all_track_defs_have_fixed_component);

    // If the template is invalid because it contains multiple auto-repetition definitions or it combines an auto-repetition
    // definition with non-fixed-size track sizing functions, then disregard it entirely and default to zero explicit tracks
    if (!template_is_valid) {
        return .{ 0, 0 };
    }

    // If there are no repetitions, then the number of explicit tracks is simply equal to the lengths of the track definition
    // vector (as each item in the Vec represents one track).
    if (auto_repetition_count == 0) {
        return .{ 0, non_auto_repeating_track_count };
    }

    var auto_repeat_insertion_point: u32 = 0;
    const repetition_definition = for (template) |def| {
        switch (def) {
            .single => auto_repeat_insertion_point +|= 1,
            .repeat => |repeat| switch (repeat.getCount()) {
                .count => |count| auto_repeat_insertion_point +|= @as(u32, count) * @as(u32, repeat.getTrackCount()),
                .auto_fit, .auto_fill => break repeat,
            },
        }
    } else unreachable;
    const repetition_definition_tracks = repetition_definition.getTracks();
    const repetition_track_count: u16 = @intCast(@min(repetition_definition_tracks.len, @as(usize, std.math.maxInt(u16))));

    // Determine the number of repetitions
    const num_repetitions_u32: u32 = if (auto_fit_container_size) |inner_container_size| blk: {
        const parent_size: ?f32 = inner_container_size;

        var non_repeating_track_used_space: f32 = -0.0;
        for (template) |track_def| {
            non_repeating_track_used_space += switch (track_def) {
                .single => |sizing_function| trackDefiniteValue(sizing_function, parent_size, calc_resolver),
                .repeat => |repeat| switch (repeat.getCount()) {
                    .count => |count| inner: {
                        var sum: f32 = -0.0;
                        for (repeat.getTracks()) |sizing_function| {
                            sum += trackDefiniteValue(sizing_function, parent_size, calc_resolver);
                        }
                        break :inner sum * @as(f32, @floatFromInt(count));
                    },
                    .auto_fit, .auto_fill => 0.0,
                },
            };
        }
        const gap_size = resolveOrZero(style.getGap().getAbs(axis), @as(?f32, inner_container_size), calc_resolver);

        // Compute the amount of space that a single repetition of the repeated track list takes
        var per_repetition_track_used_space: f32 = -0.0;
        for (repetition_definition_tracks) |sizing_function| {
            per_repetition_track_used_space += trackDefiniteValue(sizing_function, parent_size, calc_resolver);
        }

        // We special case the first repetition here because the number of gaps in the first repetition
        // depends on the number of non-repeating tracks in the template
        const first_repetition_and_non_repeating_tracks_used_space = non_repeating_track_used_space +
            per_repetition_track_used_space +
            (@as(f32, @floatFromInt((@as(u32, non_auto_repeating_track_count) + @as(u32, repetition_track_count)) -| 1)) * gap_size);

        // If a single repetition already overflows the container then we return 1 as the repetition count
        // (the number of repetitions is floored at 1)
        if (first_repetition_and_non_repeating_tracks_used_space > inner_container_size) {
            break :blk 1;
        } else {
            const per_repetition_gap_used_space = @as(f32, @floatFromInt(repetition_track_count)) * gap_size;
            const per_repetition_used_space = per_repetition_track_used_space + per_repetition_gap_used_space;
            const num_repetition_that_fit = (inner_container_size - first_repetition_and_non_repeating_tracks_used_space) /
                per_repetition_used_space;

            // If the container size is a preferred or maximum size:
            //   Then we return the maximum number of repetitions that fit into the container without overflowing.
            // If the container size is a minimum size:
            //   - Then we return the minimum number of repetitions required to overflow the size.
            //
            // In all cases we add the additional repetition that was already accounted for in the special-case computation above
            // Note: as-casts from f32 to u32 saturate, so a huge or infinite number of repetitions
            // (e.g. due to zero-sized tracks) resolves to u32::MAX and is clamped below
            break :blk switch (auto_fit_strategy) {
                .max_repetitions_that_do_not_overflow => saturatingU32(sys.floor(num_repetition_that_fit)) +| 1,
                .min_repetitions_that_do_overflow => saturatingU32(sys.ceil(num_repetition_that_fit)) +| 1,
            };
        }
    } else 1;

    // Clamp the number of repetitions based on the auto-repeat's insertion point so that tracks
    // before it are preserved and tracks after it are truncated in source order.
    // https://www.w3.org/TR/css-grid-1/#overlarge-grids
    const remaining_tracks = @as(u32, max_grid_tracks) -| auto_repeat_insertion_point;
    const num_repetitions: u16 = if (remaining_tracks == 0) 0 else blk: {
        const max_repetitions = std.math.divCeil(u32, remaining_tracks, repetition_track_count) catch unreachable;
        break :blk @intCast(std.math.clamp(num_repetitions_u32, 1, max_repetitions));
    };

    const grid_template_track_count: u16 = @intCast(@min(
        @as(u32, non_auto_repeating_track_count) + (@as(u32, repetition_track_count) * @as(u32, num_repetitions)),
        @as(u32, max_grid_tracks),
    ));
    return .{ num_repetitions, grid_template_track_count };
}

/// Rust's saturating `f32 as u32` cast (NaN becomes 0)
fn saturatingU32(value: f32) u32 {
    if (std.math.isNan(value)) return 0;
    if (value <= 0.0) return 0;
    if (value >= 4294967295.0) return std.math.maxInt(u32);
    return @intFromFloat(value);
}

/// Resolve the track sizing functions of explicit tracks, automatically created tracks, and gutters
/// given a set of track counts and all of the relevant styles
///
/// `track_has_items` is any value with a `call(self, track_index: usize) bool` method.
pub fn initializeGridTracks(
    gpa: Allocator,
    tracks: *std.ArrayList(GridTrack),
    counts: TrackCounts,
    style: anytype,
    axis: AbsoluteAxis,
    auto_repetition_count: u16,
    track_has_items: anytype,
) LayoutError!void {
    // Extract styles
    const track_template: ?[]const GridTemplateComponent, const auto_tracks: []const TrackSizingFunction, const gap: LengthPercentage = switch (axis) {
        .horizontal => .{ style.getGridTemplateColumns(), style.getGridAutoColumns(), style.getGap().width },
        .vertical => .{ style.getGridTemplateRows(), style.getGridAutoRows(), style.getGap().height },
    };

    // Clear vector (in case this is a re-layout), reserve space for all tracks ahead of time to reduce allocations,
    // and push the initial gutter
    tracks.clearRetainingCapacity();
    try tracks.ensureTotalCapacity(gpa, (counts.len() * 2) + 1);
    try tracks.append(gpa, GridTrack.gutter(gap));

    const auto_track_count = auto_tracks.len;

    // Create negative implicit tracks
    if (counts.negative_implicit > 0) {
        if (auto_track_count == 0) {
            try createImplicitTracks(gpa, tracks, counts.negative_implicit, &.{TrackSizingFunction.auto}, 0, gap);
        } else {
            const offset = auto_track_count - (@as(usize, counts.negative_implicit) % auto_track_count);
            try createImplicitTracks(gpa, tracks, counts.negative_implicit, auto_tracks, offset, gap);
        }
    }

    var current_track_index: usize = counts.negative_implicit;

    // The maximum index up to which explicit tracks may be created. The explicit track count is clamped
    // to MAX_GRID_TRACKS, so track creation from the template must be truncated to match.
    const explicit_track_limit: usize = counts.negative_implicit + counts.explicit;

    // Create explicit tracks
    // An explicit check against the count (rather than just relying on track_template being empty) is required here
    // because a count of zero can result from the track_template being invalid, in which case it should be ignored.
    if (counts.explicit > 0) {
        if (track_template) |template| {
            for (template) |track_sizing_function| {
                switch (track_sizing_function) {
                    .single => |sizing_function| {
                        if (current_track_index < explicit_track_limit) {
                            try tracks.append(gpa, GridTrack.new(sizing_function.minSizingFunction(), sizing_function.maxSizingFunction()));
                            try tracks.append(gpa, GridTrack.gutter(gap));
                            current_track_index += 1;
                        }
                    },
                    .repeat => |repeat| switch (repeat.getCount()) {
                        .count => |count| {
                            const repeated_track_count = @min(
                                @as(usize, repeat.getTrackCount()) * @as(usize, count),
                                explicit_track_limit - current_track_index,
                            );
                            const repeat_tracks = repeat.getTracks();
                            for (0..repeated_track_count) |i| {
                                const sizing_function = repeat_tracks[i % repeat_tracks.len];
                                try tracks.append(gpa, GridTrack.new(sizing_function.minSizingFunction(), sizing_function.maxSizingFunction()));
                                try tracks.append(gpa, GridTrack.gutter(gap));
                                current_track_index += 1;
                            }
                        },
                        .auto_fit, .auto_fill => {
                            const auto_repeated_track_count = @min(
                                @as(usize, repeat.getTrackCount()) * @as(usize, auto_repetition_count),
                                explicit_track_limit - current_track_index,
                            );
                            const repeat_tracks = repeat.getTracks();
                            for (0..auto_repeated_track_count) |i| {
                                const track_def = repeat_tracks[i % repeat_tracks.len];
                                var track = GridTrack.new(track_def.minSizingFunction(), track_def.maxSizingFunction());
                                var gutter = GridTrack.gutter(gap);

                                // Auto-fit tracks that don't contain should be collapsed.
                                if (repeat.getCount() == .auto_fit and !track_has_items.call(current_track_index)) {
                                    track.collapse();
                                    gutter.collapse();
                                }

                                try tracks.append(gpa, track);
                                try tracks.append(gpa, gutter);

                                current_track_index += 1;
                            }

                            // Is this auto-repeat at the very end of the track list?
                            const is_last = current_track_index == counts.len();

                            // When collapsing auto-fit tracks (in the loop just above), we collapse the gutter after collapsed
                            // tracks but not the gutter before. This is correct so long as there is another non-collapsed track
                            // somewhere in the track list after the collapsed track.
                            //
                            // However, if the auto-fit repeat is at the very end of the track list, then there will be no such track.
                            // In this case we need to iterate backwards through the track list until we find a non-collapsed track and
                            // collapse the gutter just after that track.
                            //
                            // As all of the other tracks and gutters we find along the way will already be collapsed, we simplify the
                            // implementation to collapsing all tracks and gutters until we find the first non-collapsed track.
                            if (repeat.getCount() == .auto_fit and is_last) {
                                var i = tracks.items.len;
                                while (i > 0) {
                                    i -= 1;
                                    const previous_track = &tracks.items[i];
                                    if (previous_track.kind == .track and !previous_track.is_collapsed) {
                                        break;
                                    }
                                    previous_track.collapse();
                                }
                            }
                        },
                    },
                }
            }
        }
    }

    const grid_area_tracks: u16 = (counts.negative_implicit + counts.explicit) - @as(u16, @intCast(current_track_index));

    // Create positive implicit tracks
    if (auto_track_count == 0) {
        try createImplicitTracks(gpa, tracks, counts.positive_implicit + grid_area_tracks, &.{TrackSizingFunction.auto}, 0, gap);
    } else {
        try createImplicitTracks(gpa, tracks, counts.positive_implicit + grid_area_tracks, auto_tracks, 0, gap);
    }

    // Mark first and last grid lines as collapsed
    tracks.items[0].collapse();
    tracks.items[tracks.items.len - 1].collapse();
}

/// Utility function for repeating logic of creating implicit tracks. The implicit track definitions
/// cycle through `auto_tracks`, starting at index `offset` (upstream passes a `cycle().skip(offset)`
/// iterator).
fn createImplicitTracks(
    gpa: Allocator,
    tracks: *std.ArrayList(GridTrack),
    count: u16,
    auto_tracks: []const TrackSizingFunction,
    offset: usize,
    gap: LengthPercentage,
) LayoutError!void {
    for (0..count) |i| {
        const track_def = auto_tracks[(offset + i) % auto_tracks.len];
        try tracks.append(gpa, GridTrack.new(track_def.minSizingFunction(), track_def.maxSizingFunction()));
        try tracks.append(gpa, GridTrack.gutter(gap));
    }
}

