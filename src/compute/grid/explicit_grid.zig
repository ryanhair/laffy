/// The calc resolver used by the upstream tests (`|_, _| 42.42`)
const Calc4242 = struct {
    pub fn resolveCalcValue(_: Calc4242, _: *const anyopaque, _: f32) f32 {
        return 42.42;
    }
};

fn len(value: f32) TrackSizingFunction {
    return TrackSizingFunction.fromLength(value);
}

fn repeatOf(count: RepetitionCount, tracks: []const TrackSizingFunction) GridTemplateComponent {
    return .{ .repeat = .{ .count = count, .tracks = tracks } };
}

fn preferredSize(style: *const Style) Size(?f32) {
    return .{ .width = style.size.width.intoOption(), .height = style.size.height.intoOption() };
}

fn explicitSizes(style: *const Style, size: Size(?f32), strategy: AutoRepeatStrategy) struct { ExplicitGridSize, ExplicitGridSize } {
    return .{
        computeExplicitGridSizeInAxis(style, size.getAbs(.horizontal), strategy, Calc4242{}, .horizontal),
        computeExplicitGridSizeInAxis(style, size.getAbs(.vertical), strategy, Calc4242{}, .vertical),
    };
}

fn expectSizes(actual: struct { ExplicitGridSize, ExplicitGridSize }, col_count: u16, row_count: u16, auto_col_reps: u16, auto_row_reps: u16) !void {
    try testing.expectEqual(col_count, actual[0][1]);
    try testing.expectEqual(row_count, actual[1][1]);
    try testing.expectEqual(auto_col_reps, actual[0][0]);
    try testing.expectEqual(auto_row_reps, actual[1][0]);
}

