var calc_handle: u64 align(8) = 0;

/// Resolves the `min(100%, 300px)` calc handle of the test below
const Min100Percent300px = struct {
    pub fn resolveCalcValue(_: Min100Percent300px, ptr: *const anyopaque, basis: f32) f32 {
        std.debug.assert(ptr == @as(*const anyopaque, &calc_handle));
        return @min(basis, 300.0);
    }
};

// `repeat(auto-fit, minmax(min(100%, 300px), 1fr))`: a `calc()` min track sizing function is a
// fixed sizing function, so the template is valid and the repetition count uses its resolved
// value (here two 300px tracks and a 8px gap fit in 800px).
test "explicit grid sizing auto fit calc min track" {
    const calc_ptr: *const anyopaque = &calc_handle;
    for ([_]RepetitionCount{ .auto_fit, .auto_fill }) |count| {
        const tracks = [_]TrackSizingFunction{.{ .min = MinTrackSizingFunction.calc(calc_ptr), .max = MaxTrackSizingFunction.fr(1.0) }};
        const cols = [_]GridTemplateComponent{repeatOf(count, &tracks)};
        var grid_style: Style = .{ .display = .grid };
        grid_style.size = .{ .width = .length(800.0), .height = .auto };
        grid_style.gap = .{ .width = .length(8.0), .height = .zero };
        grid_style.grid_template_columns = &cols;
        try testing.expectEqual(ExplicitGridSize{ 2, 2 }, computeExplicitGridSizeInAxis(&grid_style, 800.0, .max_repetitions_that_do_not_overflow, Min100Percent300px{}, .horizontal));

        // The calc() resolves against the container: in a 250px container it is 250px, one track
        try testing.expectEqual(ExplicitGridSize{ 1, 1 }, computeExplicitGridSizeInAxis(&grid_style, 250.0, .max_repetitions_that_do_not_overflow, Min100Percent300px{}, .horizontal));
    }
}

